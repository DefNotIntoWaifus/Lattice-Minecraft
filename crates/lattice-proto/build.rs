//! Generates packet ID constants from Mojang's packet report
//! (crates/lattice-data/data/packets.json, produced by tools/gen-data.sh).

use std::{env, fmt::Write, fs, path::PathBuf};

fn main() {
    let src = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../lattice-data/data/packets.json");
    println!("cargo:rerun-if-changed={}", src.display());
    let json: serde_json::Value = serde_json::from_str(&fs::read_to_string(&src).expect("packets.json")).unwrap();

    let mut out = String::from("// @generated by build.rs from packets.json — do not edit.\n");
    for (state, dirs) in json.as_object().unwrap() {
        writeln!(out, "pub mod {state} {{").unwrap();
        for (dir, packets) in dirs.as_object().unwrap() {
            let module = if dir == "clientbound" { "cb" } else { "sb" };
            writeln!(out, "    pub mod {module} {{").unwrap();
            let mut list: Vec<(String, i64)> = packets
                .as_object()
                .unwrap()
                .iter()
                .map(|(k, v)| (k.trim_start_matches("minecraft:").to_string(), v["protocol_id"].as_i64().unwrap()))
                .collect();
            list.sort_by_key(|(_, id)| *id);
            for (name, id) in &list {
                let ident = name.replace(['/', '.'], "_").to_uppercase();
                writeln!(out, "        pub const {ident}: i32 = {id:#04x};").unwrap();
            }
            writeln!(out, "        pub fn name(id: i32) -> &'static str {{ match id {{").unwrap();
            for (name, id) in &list {
                writeln!(out, "            {id:#04x} => \"{name}\",").unwrap();
            }
            writeln!(out, "            _ => \"unknown\", }} }}").unwrap();
            writeln!(out, "    }}").unwrap();
        }
        writeln!(out, "}}").unwrap();
    }
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("ids.rs"), out).unwrap();
}
